namespace CanopyX;

/// <summary>The logical text alignment of a column's header and cells.</summary>
public enum CanopyColumnAlignment {
    /// <summary>The start edge: left in left-to-right text, right in right-to-left text.</summary>
    Start,
    /// <summary>Centred.</summary>
    Center,
    /// <summary>The end edge: right in left-to-right text, left in right-to-left text.</summary>
    End
}
