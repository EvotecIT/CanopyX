// The TypeScript API report: every declaration file the npm package ships, without comments and with one top-level
// statement per line, in api/canopyx.d.ts.txt. `node tools/api-report.mjs` checks the report against the declarations and
// fails on a difference, so a changed signature shows in review while comment edits do not; `--update` rewrites it after
// an intended change (see docs/versioning.md). The strict consumer in the package smoke checks that the declarations
// compile. Validation tooling only, never part of the library build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const report = path.join(repo, "api/canopyx.d.ts.txt");
const manifest = JSON.parse(fs.readFileSync(path.join(repo, "package.json"), "utf8"));

// The shipped declaration files, from the package's file patterns (folder/*.d.ts).
const files = manifest.files.filter(pattern => pattern.endsWith("*.d.ts")).flatMap(pattern => {
  const folder = path.join(repo, path.dirname(pattern));
  return fs.readdirSync(folder).filter(name => name.endsWith(".d.ts")).sort().map(name => path.join(folder, name));
});

/** Drops comments and collapses white space, keeping strings intact; one top-level statement per line. */
function normalize(source) {
  let out = "", depth = 0, i = 0, space = false;
  const emit = text => { if (space && out && !out.endsWith("\n")) out += " "; space = false; out += text; };
  while (i < source.length) {
    const char = source[i], next = source[i + 1];
    if (char === "/" && next === "/") { while (i < source.length && source[i] !== "\n") i++; space = true; continue; }
    if (char === "/" && next === "*") {
      // A deprecation is part of the API: the comment goes, its mark stays.
      const end = source.indexOf("*/", i + 2), comment = source.slice(i, end < 0 ? source.length : end);
      if (comment.includes("@deprecated")) emit("/** @deprecated */");
      i = end < 0 ? source.length : end + 2; space = true; continue;
    }
    if (char === "\"" || char === "'" || char === "`") {
      let j = i + 1;
      while (j < source.length && source[j] !== char) j += source[j] === "\\" ? 2 : 1;
      emit(source.slice(i, j + 1)); i = j + 1; continue;
    }
    if (/\s/.test(char)) { space = true; i++; continue; }
    if (char === "{" || char === "(" || char === "[") depth++;
    if (char === "}" || char === ")" || char === "]") depth--;
    // The members of a top-level interface or type literal go one per line, indented.
    if (char === "}" && depth === 0 && !out.endsWith("\n")) out += "\n";
    emit(char); i++;
    if (depth === 1 && (char === "{" || char === ";")) { out += "\n  "; space = false; }
    // A statement ends at a semicolon or a closing brace back at the top level.
    if (depth === 0 && (char === ";" || char === "}")) { out += "\n"; space = false; }
  }
  return out.split("\n").map(line => line.trimEnd()).filter(line => line.trim())
    // Spacing around punctuation does not change an API; text inside string literal types stays as written.
    .map(line => (line.startsWith("  ") ? "  " : "") + line.trim().split(/("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`)/)
      .map((part, index) => index % 2 ? part : part.replace(/\s*([{}()[\]<>,;:|&=?])\s*/g, "$1").replace(/=>/g, " => ")).join("")).join("\n");
}

const lines = ["// The public TypeScript API of " + manifest.name + ", generated by tests/browser/tools/api-report.mjs. Do not edit by hand:",
  "// run `node tools/api-report.mjs --update` in tests/browser after an intended change, and review the difference."];
for (const file of files) lines.push("", "// ---- " + path.relative(repo, file).replace(/\\/g, "/") + " ----", normalize(fs.readFileSync(file, "utf8")));
const text = lines.join("\n") + "\n";

if (process.argv.includes("--update")) {
  fs.mkdirSync(path.dirname(report), { recursive: true });
  fs.writeFileSync(report, text);
  console.log("TypeScript API report written: " + path.relative(repo, report).replace(/\\/g, "/"));
} else {
  const current = fs.existsSync(report) ? fs.readFileSync(report, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    const before = new Set(current.split("\n")), after = new Set(text.split("\n"));
    console.error("The public TypeScript API changed without an updated report (api/canopyx.d.ts.txt).");
    for (const line of [...before].filter(line => !after.has(line)).slice(0, 20)) console.error("- " + line.slice(0, 240));
    for (const line of [...after].filter(line => !before.has(line)).slice(0, 20)) console.error("+ " + line.slice(0, 240));
    console.error("Run `node tools/api-report.mjs --update` in tests/browser if the change is intended, and follow docs/versioning.md.");
    process.exit(1);
  }
  console.log("TypeScript API report matches: " + files.length + " declaration files.");
}
