namespace CanopyX.Html.Ui;

/// <summary>Where a carousel's Previous and Next buttons sit.</summary>
public enum CanopyCarouselControlPosition {
    /// <summary>In a bar under the slides. The default.</summary>
    Below,
    /// <summary>In a bar above the slides.</summary>
    Above,
    /// <summary>Beside the slides, Previous at the start edge and Next at the end edge; a Pause button stays in the bar below.</summary>
    Sides
}
