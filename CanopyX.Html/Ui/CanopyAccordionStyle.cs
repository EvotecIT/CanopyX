namespace CanopyX.Html.Ui;

/// <summary>The accordion's visual treatment.</summary>
public enum CanopyAccordionStyle {
    /// <summary>A bordered card with lines between sections.</summary>
    Default,
    /// <summary>Lines between sections and no outer border, for use inside a card or panel.</summary>
    Flush,
    /// <summary>Each section is its own card, with space between them.</summary>
    Separated,
    /// <summary>Larger headings without borders, for page sections.</summary>
    Section
}
