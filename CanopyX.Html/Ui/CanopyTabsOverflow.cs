namespace CanopyX.Html.Ui;

/// <summary>Overflow treatment for a tab list.</summary>
public enum CanopyTabsOverflow {
    /// <summary>Scrolls the tab list.</summary>
    Scroll,
    /// <summary>Moves overflowing tabs into a menu.</summary>
    Menu,
    /// <summary>Wraps pills onto additional lines.</summary>
    Wrap,
}
